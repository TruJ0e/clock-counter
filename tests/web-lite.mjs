// Local-file browser edition regression tests (no web server or Electron).
import assert from 'node:assert/strict';
import {chromium} from 'playwright-core';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import fs from 'node:fs/promises';

const root=path.resolve(import.meta.dirname,'..');
const file=process.env.CLOCK_COUNTER_WEB_TEST_HTML||path.join(root,'dist','CLOCK COUNTER WEB LITE.html');
const edge='C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe';
await fs.access(file); await fs.access(edge);
const browser=await chromium.launch({executablePath:edge,headless:true});
const context=await browser.newContext({acceptDownloads:true});
const page=await context.newPage();
const errors=[];
page.on('pageerror',err=>errors.push(err.message));
page.on('console',msg=>{if(msg.type()==='error')errors.push(msg.text())});
try{
  await page.goto(pathToFileURL(file).href);
  await page.locator('.clock-tile').first().waitFor({timeout:12000});
  assert.equal(await page.title(),'CLOCK COUNTER — Browser Edition');
  assert.equal(await page.locator('#update-trigger').isVisible(),false);

  assert.equal(await page.locator('.time-readout').first().textContent(),'30:00');
  await page.locator('#add-clock').click();
  assert.equal(await page.locator('.clock-tile').count(),2);
  await page.locator('.clock-tile').nth(1).locator('.minutes-field').fill('5');
  await page.locator('.clock-tile').nth(1).locator('.minutes-field').blur();
  assert.equal(await page.locator('.clock-tile').nth(1).locator('.time-readout').textContent(),'05:00');
  await page.locator('.clock-tile').nth(1).locator('.play-pause').click();
  assert.equal(await page.locator('.clock-tile').nth(1).getAttribute('data-running'),'true');
  assert.equal(await page.locator('.clock-tile').nth(1).locator('.controls-drawer').getAttribute('data-collapsed'),'true');
  await page.locator('#file-trigger').click();
  await page.locator('#menu-library').click();
  await page.locator('#preset-name').fill('Five minutes');
  await page.locator('#preset-minutes').fill('5');
  await page.locator('#preset-save').click();
  assert.ok((await page.locator('#presets-list').textContent()).includes('Five minutes'));
  await page.locator('#library-done').click();
  await page.locator('#file-trigger').click();
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#menu-export').click();
  const download=await downloadPromise;
  assert.equal(download.suggestedFilename(),'clock-counter-setup.json');
  await page.locator('#clock-only').click();
  assert.equal(await page.locator('#app-shell').evaluate(el=>el.classList.contains('clock-only')),true);
  await page.locator('#focus-restore').click();
  assert.equal(await page.locator('#app-shell').evaluate(el=>el.classList.contains('clock-only')),false);
  await page.locator('.clock-tile').first().locator('.tile-settings').click();
  await page.locator('#setting-mode').selectOption('stopwatch');
  await page.locator('#done-settings').click();
  assert.equal(await page.locator('.clock-tile').first().getAttribute('data-mode'),'stopwatch');
  await page.reload();
  await page.locator('.clock-tile').first().waitFor();
  assert.equal(await page.locator('.clock-tile').count(),2);
  assert.equal(await page.locator('.clock-tile').first().getAttribute('data-mode'),'stopwatch');
  await page.locator('#file-trigger').click();
  await page.locator('#menu-library').click();
  assert.ok((await page.locator('#presets-list').textContent()).includes('Five minutes'));
  await page.locator('#library-done').click();
  assert.deepEqual(errors,[]);
  console.log('PASS web-lite offline browser app: multi-clock, presets, stopwatch, downloads, clock-only mode, drawer, saved settings.');
  console.log('WEB_LITE_FILE_BYTES '+(await fs.stat(file)).size);
}finally{await browser.close();}
